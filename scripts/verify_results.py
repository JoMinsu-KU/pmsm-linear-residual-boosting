"""Standard-library review-bundle verifier. Does not train, unpickle or infer."""
from pathlib import Path
import json,hashlib,statistics,math,csv
M=Path(__file__).resolve().parents[1]/'results'
read=lambda p:json.loads(p.read_text(encoding='utf-8-sig'))
checks=0;failures=[]
def check(label,value):
    global checks
    checks+=1
    if not value:failures.append(label)
def eq(label,a,b):check(label,math.isclose(float(a),float(b),abs_tol=2e-12,rel_tol=2e-13))
manifest=read(M/'SHA256SUMS.json')
for entry in manifest['files']:
    p=M/entry['path']
    check('safe path '+entry['path'],p.resolve().is_relative_to(M.resolve()))
    check('hash '+entry['path'],p.is_file() and hashlib.sha256(p.read_bytes()).hexdigest()==entry['sha256'])
raw={ds:read(M/f'analysis/{ds}-own-evaluation-source.json') for ds in ['ipmsm','paderborn']}
with (M/'tables/S1-own-accuracy-all-methods.csv').open(encoding='utf-8',newline='') as f:
    table={(r['dataset'],r['role'],r['method']):r for r in csv.DictReader(f)}
for ds,d in raw.items():
    for cohort in d['roles']:
        records=[p for p in d['per_profile'] if p['role']==cohort['role']]
        for method,v in cohort['methods'].items():
            rows=[p['methods'][method] for p in records]
            macro=statistics.fmean(r['rmse'] for r in rows)
            pooled=math.sqrt(sum(r['mse']*r['n'] for r in rows)/sum(r['n'] for r in rows))
            label=ds+'/'+cohort['role']+'/'+method
            eq(label+' macro JSON',macro,v['macro_rmse']);eq(label+' pooled JSON',pooled,v['pooled_rmse'])
            eq(label+' macro CSV',macro,table[(ds,cohort['role'],method)]['macro_rmse'])
mapping={'L':'linear_residual','H':'linear_half','D9':'d9','D':'d9','direct200':'direct200','capacity':'capacity_direct','capacity_direct':'capacity_direct','free_half':'free_half','free25_half':'free_half'}
def value(p,key):
    if 'mlp' in key.lower():return statistics.fmean(p['methods'][f'mse_mlp_{s}']['rmse'] for s in [2026111701,2026111702,2026111703])
    return p['methods'][mapping.get(key,key)]['rmse']
influence=read(M/'analysis/c18-influence-review-v001.json')
for c in influence['comparisons']:
    records=[p for p in raw[c['dataset']]['per_profile'] if p['role']==c['role']]
    delta={p['profile']:value(p,c['candidate'])-value(p,c['baseline']) for p in records}
    eq('influence mean',statistics.fmean(delta.values()),c['macro_delta_c'])
    eq('wins',sum(v<0 for v in delta.values()),c['wins']);eq('losses',sum(v>0 for v in delta.values()),c['losses'])
    deletions={i:statistics.fmean(v for j,v in delta.items() if j!=i) for i in delta}
    eq('deletion min',min(deletions.values()),c['deletion_min_delta_c']);eq('deletion max',max(deletions.values()),c['deletion_max_delta_c'])
    for row in c['per_profile']:eq('profile difference',delta[row['profile']],row['delta_c'])
    for row in c['all_single_profile_deletions']:
        eq('deleted profile difference',delta[row['deleted_profile']],row['deleted_profile_delta_c'])
        eq('remaining mean',deletions[row['deleted_profile']],row['remaining_macro_delta_c'])
cost=read(M/'analysis/cost-comparison-source.json')
inventory=read(M/'reproducibility/deployment-artifacts-v001.json')
for panel in inventory['panels']:
    c=next(c for c in cost['panels'] if c['dataset']==panel['dataset'] and c['arm']==('own' if panel['arm']=='own_boundary' else panel['arm']))
    for method,v in panel['methods'].items():eq('inventory byte summary',v['total_unique_bytes'],c['methods'][method]['artifact_bytes'])
    v=panel['methods'];proof=panel['H_union_proof']
    eq('H byte union',v['H']['total_unique_bytes'],v['D']['total_unique_bytes']+v['L']['total_unique_bytes']-proof['overlap_bytes'])
report={'status':'PASS' if not failures else 'FAIL','checks':checks,'failures':failures,'scope':'Bundle integrity and saved-metric arithmetic only. Original predictions, training, timings and literature claims are not independently regenerated by this script.'}
print(json.dumps(report,indent=2))
raise SystemExit(0 if not failures else 1)
